/**
 * Заливает стартовый контент только если база пустая.
 * Вызывается при старте сервера.
 */
export function seedIfEmpty() {
  const memesCount = memesRepo.count();
  const promptsCount = promptsRepo.count();

  if (memesCount === 0) {
    memesRepo.insertMany(STARTER_MEMES);
    log('seed', `Мемов добавлено: ${STARTER_MEMES.length}`);
  } else {
    log('seed', `Мемы уже есть (${memesCount}), пропускаю`);
  }

  if (promptsCount === 0) {
    promptsRepo.insertMany(STARTER_PROMPTS);
    log('seed', `Заданий добавлено: ${STARTER_PROMPTS.length}`);
  } else {
    log('seed', `Задания уже есть (${promptsCount}), пропускаю`);
  }
}

/**
 * Принудительно заливает стартовые данные (upsert).
 * Существующие записи с теми же id обновятся.
 */
export function forceSeed() {
  memesRepo.insertMany(STARTER_MEMES);
  promptsRepo.insertMany(STARTER_PROMPTS);
  log('seed', `Форс-сид: мемов ${STARTER_MEMES.length}, заданий ${STARTER_PROMPTS.length}`);
}

// ============================================================
// CLI-режим: node server/seed.js [--force]
// ============================================================

const isMain = import.meta.url === `file://${process.argv[1]}`;

if (isMain) {
  const force = process.argv.includes('--force');
  try {
    if (force) {
      forceSeed();
    } else {
      seedIfEmpty();
    }
    log('seed', 'Готово');
  } catch (e) {
    log('seed', 'Ошибка:', e.message);
    process.exit(1);
  }
}